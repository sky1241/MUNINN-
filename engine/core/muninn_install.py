def _is_muninn_hook_entry(entry: dict) -> bool:
    """Heuristic: does this hook entry belong to muninn?

    We look for our installed hook filenames in the `command` string or
    for the literal `python -m muninn` invocation (pip-installed mode).
    """
    cmd = entry.get("command", "") if isinstance(entry, dict) else ""
    if not isinstance(cmd, str):
        return False
    # Pip-installed signature
    if "python -m muninn" in cmd or "muninn-mem" in cmd:
        return True
    # File-path signature: any of our installed hook filenames
    for fname in _MUNINN_INSTALLED_HOOK_FILES:
        if fname in cmd:
            return True
    return False


def uninstall_hooks(repo_path, purge_data: bool = False) -> dict:
    """Remove everything Muninn installed in a repo. Companion to install_hooks().

    Steps :
        1. Strip muninn-owned entries from `.claude/settings.local.json` (preserves
           the user's own hooks under the same event names).
        2. Delete `.claude/hooks/*.py` files generated by install_hooks().
        3. Uninstall the systemd-user `muninn-prune.timer` (if present).
        4. If `purge_data=True`, also remove `.muninn/` (user data).
           Default is False — user data is the user's, not ours to delete.

    Returns a dict report (counts of removed items) for the CLI to print.
    """
    repo_path = Path(repo_path).resolve()
    report = {
        "settings_entries_removed": 0,
        "hook_files_removed": [],
        "cron_uninstalled": False,
        "data_purged": False,
        "warnings": [],
    }

    # 1. Strip muninn entries from settings.local.json
    settings_path = repo_path / ".claude" / "settings.local.json"
    if settings_path.exists():
        try:
            settings = json.loads(settings_path.read_text(encoding="utf-8"))
        except Exception as exc:
            report["warnings"].append(
                f"could not parse {settings_path}: {exc}"
            )
            settings = None
        if settings is not None:
            hooks = settings.get("hooks", {})
            removed = 0
            for event_name in list(hooks.keys()):
                if event_name not in _MUNINN_HOOK_EVENTS:
                    continue
                # Two layouts: list of dicts (simple events) OR list of
                # {matcher, hooks: [...]} (PreToolUse/PostToolUse-style).
                entries = hooks[event_name]
                if not isinstance(entries, list):
                    continue
                new_entries = []
                for e in entries:
                    if isinstance(e, dict) and "hooks" in e and isinstance(e["hooks"], list):
                        # Matcher format
                        kept = [h for h in e["hooks"] if not _is_muninn_hook_entry(h)]
                        removed += len(e["hooks"]) - len(kept)
                        if kept:
                            new_entries.append({**e, "hooks": kept})
                    else:
                        if _is_muninn_hook_entry(e):
                            removed += 1
                        else:
                            new_entries.append(e)
                if new_entries:
                    hooks[event_name] = new_entries
                else:
                    # No remaining entries for this event → drop the key entirely
                    del hooks[event_name]
            if removed > 0:
                # Write back atomically
                tmp = settings_path.with_suffix(".json.tmp")
                tmp.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8")
                tmp.replace(settings_path)
                report["settings_entries_removed"] = removed

    # 2. Delete hook .py files
    hooks_dir = repo_path / ".claude" / "hooks"
    if hooks_dir.exists():
        for f in sorted(hooks_dir.iterdir()):
            if f.is_file() and f.name in _MUNINN_INSTALLED_HOOK_FILES:
                try:
                    f.unlink()
                    report["hook_files_removed"].append(f.name)
                except Exception as exc:
                    report["warnings"].append(f"could not delete {f}: {exc}")

    # 3. Uninstall systemd timer (delegates to install_cron with uninstall=True)
    try:
        cron_result = install_cron(repo_path, uninstall=True)
        if cron_result.get("removed_files"):
            report["cron_uninstalled"] = True
    except Exception as exc:
        report["warnings"].append(f"install_cron(uninstall=True) failed: {exc}")

    # 4. Optionally purge user data
    if purge_data:
        data_dir = repo_path / ".muninn"
        if data_dir.exists():
            import shutil
            try:
                shutil.rmtree(data_dir)
                report["data_purged"] = True
            except Exception as exc:
                report["warnings"].append(f"could not remove {data_dir}: {exc}")

    return report


