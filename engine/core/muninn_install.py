def _find_recent_branches(tree_dir, n):
    """Return up to n (name, text) tuples for the n most recently modified branches.

    "Recent" is a cheap proxy for "hot" — branches touched in the last session
    are most likely relevant when Claude wakes up. Sorted by st_mtime desc.
    """
    branches = []
    try:
        for bf in tree_dir.glob("*.mn"):
            if bf.name == "root.mn":
                continue
            try:
                branches.append((bf.stat().st_mtime, bf))
            except OSError:
                continue
    except OSError:
        return []
    branches.sort(key=lambda t: t[0], reverse=True)
    selected = []
    for _mtime, bf in branches[:n]:
        try:
            selected.append((bf.stem, bf.read_text(encoding="utf-8")))
        except OSError:
            continue
    return selected


